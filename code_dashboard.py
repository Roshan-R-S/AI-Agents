import streamlit as st
from crewai import Agent, Task, Crew
from crewai.llm import LLM
from dotenv import load_dotenv
from datetime import datetime
import time

load_dotenv()

# ============================================================
# PAGE CONFIGURATION
# ============================================================

st.set_page_config(
    page_title="🤖 CrewAI Code Generator",
    page_icon="🚀",
    layout="wide",
    initial_sidebar_state="expanded"
)

# Custom CSS
st.markdown("""
<style>
    .main {
        padding: 0rem 0rem;
    }
    .stTabs [data-baseweb="tab-list"] button {
        font-size: 1.2em;
        padding: 1em;
    }
</style>
""", unsafe_allow_html=True)

# ============================================================
# INITIALIZE LLM
# ============================================================

@st.cache_resource
def get_llm():
    return LLM(model="ollama/mistral", base_url="http://localhost:11434")

llm = get_llm()

# ============================================================
# AGENTS
# ============================================================

@st.cache_resource
def get_agents():
    architect = Agent(
        role="Software Architect",
        goal="Design optimal solutions for coding problems",
        backstory="You are an experienced architect who designs clean, scalable solutions",
        llm=llm
    )
    
    generator = Agent(
        role="Code Generator",
        goal="Write clean, production-ready code",
        backstory="You are an expert programmer who writes efficient, readable code",
        llm=llm
    )
    
    reviewer = Agent(
        role="Code Reviewer",
        goal="Review code for quality, security, and best practices",
        backstory="You are a meticulous code reviewer",
        llm=llm
    )
    
    debugger = Agent(
        role="Debugger",
        goal="Find and fix bugs in code",
        backstory="You are a master debugger",
        llm=llm
    )
    
    optimizer = Agent(
        role="Performance Optimizer",
        goal="Optimize code for speed and efficiency",
        backstory="You specialize in performance optimization",
        llm=llm
    )
    
    return architect, generator, reviewer, debugger, optimizer

# ============================================================
# SIDEBAR
# ============================================================

with st.sidebar:
    st.title("⚙️ Settings")
    st.markdown("---")
    
    model_choice = st.selectbox(
        "Select LLM Model",
        ["ollama/mistral", "ollama/neural-chat", "ollama/llama2"],
        help="Choose which local model to use"
    )
    
    st.markdown("---")
    st.subheader("📚 Quick Templates")
    
    templates = {
        "Factorial": "Create a function that calculates factorial with memoization",
        "Reverse String": "Build a function that reverses a string without using built-in reverse",
        "Prime Numbers": "Create a function that finds all prime numbers up to N",
        "Palindrome": "Write a function that checks if a string is a palindrome",
        "Binary Search": "Implement binary search algorithm with error handling",
        "Bubble Sort": "Create a sorting function with optimizations",
    }
    
    if st.button("📋 Show Templates"):
        st.info("**Click a template below to use it:**")
        for name, desc in templates.items():
            st.write(f"- **{name}**: {desc}")
    
    st.markdown("---")
    st.subheader("ℹ️ About")
    st.write("""
    This dashboard uses CrewAI with 5 specialized agents to:
    - Design optimal solutions
    - Generate production-ready code
    - Review code quality
    - Debug and test
    - Optimize performance
    """)

