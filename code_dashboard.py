# Tabs
tab1, tab2, tab3 = st.tabs(["💻 Generate Code", "📊 Code Analyzer", "📚 Documentation"])

# ============================================================
# TAB 1: GENERATE CODE
# ============================================================

with tab1:
    col1, col2 = st.columns([2, 1])
    
    with col1:
        st.subheader("📝 Enter Your Code Requirement")
        
        user_input = st.text_area(
            "What code do you want to generate?",
            placeholder="Example: Create a function that finds the longest word in a sentence",
            height=150,
            label_visibility="collapsed"
        )
    
    with col2:
        st.subheader("🎯 Quick Templates")
        
        selected_template = st.selectbox(
            "Or use a template:",
            ["Custom"] + list(templates.keys()),
            label_visibility="collapsed"
        )
        
        if selected_template != "Custom":
            user_input = templates[selected_template]
            st.info(f"✓ Template loaded: {selected_template}")
    
    st.markdown("---")
    
    # Generate button
    col1, col2, col3 = st.columns([1, 1, 2])
    
    with col1:
        generate_button = st.button("🚀 Generate Code", type="primary", use_container_width=True)
    
    with col2:
        clear_button = st.button("🗑️ Clear", use_container_width=True)
    
    if clear_button:
        st.rerun()
    
    if generate_button:
        if not user_input.strip():
            st.error("❌ Please enter a code requirement!")
        else:
            with st.spinner("🔄 Generating code... This may take 2-3 minutes"):
                progress_bar = st.progress(0)
                
                try:
                    architect, generator, reviewer, debugger, optimizer = get_agents()
                    
                    # Tasks
                    task_design = Task(
                        description=f"Design a solution for: {user_input}",
                        expected_output="Solution design with approach",
                        agent=architect
                    )
                    progress_bar.progress(20)
                    
                    task_generate = Task(
                        description=f"Write Python code for: {user_input}. Include docstrings, type hints, and error handling.",
                        expected_output="Complete, production-ready code",
                        agent=generator
                    )
                    progress_bar.progress(40)
                    
                    task_review = Task(
                        description="Review the generated code for quality, best practices, and security issues.",
                        expected_output="Code review with suggestions",
                        agent=reviewer
                    )
                    progress_bar.progress(60)
                    
                    task_debug = Task(
                        description="Test code with edge cases and find potential bugs.",
                        expected_output="Bug report with fixes",
                        agent=debugger
                    )
                    progress_bar.progress(80)
                    
                    task_optimize = Task(
                        description="Optimize code for performance and efficiency.",
                        expected_output="Optimized code with explanation",
                        agent=optimizer
                    )
                    progress_bar.progress(90)
                    
                    crew = Crew(agents=[architect, generator, reviewer, debugger, optimizer], tasks=[task_design, task_generate, task_review, task_debug, task_optimize])
                    
                    result = crew.kickoff()
                    progress_bar.progress(100)
                    
                    st.success("✅ Code Generated Successfully!")
                    
                    # Display results in tabs
                    st.markdown("---")
                    st.subheader("📊 Generated Code & Analysis")
                    
                    result_tabs = st.tabs(["📄 Full Result", "💾 Download"])
                    
                    with result_tabs[0]:
                        st.markdown(str(result))
                    
                    with result_tabs[1]:
                        st.download_button(
                            label="📥 Download Code as .txt",
                            data=str(result),
                            file_name=f"generated_code_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt",
                            mime="text/plain",
                            use_container_width=True
                        )
                        
                        st.download_button(
                            label="📥 Download Code as .py",
                            data=str(result),
                            file_name=f"generated_code_{datetime.now().strftime('%Y%m%d_%H%M%S')}.py",
                            mime="text/plain",
                            use_container_width=True
                        )
                
                except Exception as e:
                    st.error(f"❌ Error generating code: {str(e)}")

# ============================================================
# TAB 2: CODE ANALYZER
# ============================================================

with tab2:
    st.subheader("🔍 Analyze Existing Code")
    
    code_to_analyze = st.text_area(
        "Paste code to analyze:",
        placeholder="Paste your Python code here...",
        height=200
    )
    
    col1, col2 = st.columns([1, 3])
    
    with col1:
        analyze_button = st.button("🔍 Analyze", type="primary", use_container_width=True)
    
    if analyze_button:
        if not code_to_analyze.strip():
            st.error("❌ Please paste code to analyze!")
        else:
            with st.spinner("Analyzing code..."):
                try:
                    _, _, reviewer, debugger, optimizer = get_agents()
                    
                    task_review = Task(
                        description=f"Review this Python code: {code_to_analyze}",
                        expected_output="Code review with issues and suggestions",
                        agent=reviewer
                    )
                    
                    task_debug = Task(
                        description="Find potential bugs and edge case issues.",
                        expected_output="Bug analysis",
                        agent=debugger
                    )
                    
                    task_optimize = Task(
                        description="Suggest performance optimizations.",
                        expected_output="Optimization suggestions",
                        agent=optimizer
                    )
                    
                    crew = Crew(agents=[reviewer, debugger, optimizer], tasks=[task_review, task_debug, task_optimize])
                    result = crew.kickoff()
                    
                    st.success("✅ Analysis Complete!")
                    st.markdown(str(result))
                
                except Exception as e:
                    st.error(f"❌ Error analyzing code: {str(e)}")

